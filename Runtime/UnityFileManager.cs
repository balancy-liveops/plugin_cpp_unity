using System;
using System.Collections;
using System.IO;
using Balancy.Dictionaries;
using UnityEngine;
using UnityEngine.Networking;

namespace Balancy
{
    internal class UnityFileManager
    {
#if UNITY_WEBGL && !UNITY_EDITOR
        private static bool _preloadComplete = false;

        [AOT.MonoPInvokeCallback(typeof(LibraryMethods.General.PreloadCompleteCallback))]
        private static void OnPreloadComplete()
        {
            Debug.Log("[Balancy] IndexedDB preload completed");
            _preloadComplete = true;
        }
#endif

        public static void Init()
        {
            var resourcesPath = Path.Combine(Application.streamingAssetsPath, "Balancy/");
            var codePath = Path.Combine(Application.dataPath, "Balancy/AutoGeneratedCode/");
            var config = BalancyConfiguration.Instance;
            if (config != null && !string.IsNullOrEmpty(config.AutogeneratedCodePath))
            {
                var customPath = config.AutogeneratedCodePath;
                if (customPath.StartsWith("/"))
                    customPath = customPath.Substring(1);
                codePath = Path.Combine(Application.dataPath, customPath);
                if (!codePath.EndsWith("/"))
                    codePath += "/";
            }

            Balancy.LibraryMethods.General.balancyInitUnityFileHelper(Application.persistentDataPath, resourcesPath, codePath);
        }

        private static string GetCodePath()
        {
            var codePath = Path.Combine(Application.dataPath, "Balancy/AutoGeneratedCode/");
            var config = BalancyConfiguration.Instance;
            if (config != null && !string.IsNullOrEmpty(config.AutogeneratedCodePath))
            {
                var customPath = config.AutogeneratedCodePath;
                if (customPath.StartsWith("/"))
                    customPath = customPath.Substring(1);
                codePath = Path.Combine(Application.dataPath, customPath);
                if (!codePath.EndsWith("/"))
                    codePath += "/";
            }
            return codePath;
        }

        public static IEnumerator InitRuntime()
        {
            var codePath = GetCodePath();

#if UNITY_WEBGL && !UNITY_EDITOR
            // WebGL: resources come from StreamingAssets via UnityWebRequest preload
            var resourcesPath = Path.Combine(Application.streamingAssetsPath, "Balancy/");
            Balancy.LibraryMethods.General.balancyInitUnityFileHelper(Application.persistentDataPath, resourcesPath, codePath);
            DataObjectsManager.Init(Application.persistentDataPath, resourcesPath);

            // Preload files from IndexedDB on WebGL
            Debug.Log("[Balancy] Preloading files from IndexedDB...");
            _preloadComplete = false;
            Balancy.LibraryMethods.General.balancyPreloadFromIndexedDB(OnPreloadComplete);

            // Wait for IndexedDB preload to complete
            while (!_preloadComplete)
            {
                yield return null;
            }

            // Preload files from StreamingAssets
            Debug.Log("[Balancy] Preloading files from StreamingAssets...");
            yield return PreloadStreamingAssets(resourcesPath);
#elif UNITY_ANDROID && !UNITY_EDITOR
            // Android: use FileHelperAndroid — reads text resources from preloaded in-memory cache,
            // serves file:///android_asset/ URLs to WebView
            var streamingAssetsSubpath = "Balancy/";
            Balancy.LibraryMethods.General.balancyInitUnityFileHelperAndroid(Application.persistentDataPath, streamingAssetsSubpath, codePath);

            var resourcesPath = Path.Combine(Application.streamingAssetsPath, "Balancy/");
            DataObjectsManager.Init(Application.persistentDataPath, resourcesPath);

            // Preload text resources from StreamingAssets into C++ memory using synchronous AssetManager reads
            PreloadAndroidTextResourcesSync(streamingAssetsSubpath);
            yield return null;
#else
            // iOS, macOS, Windows, Editor: StreamingAssets are directly accessible on the filesystem
            var resourcesPath = Path.Combine(Application.streamingAssetsPath, "Balancy/");
            Balancy.LibraryMethods.General.balancyInitUnityFileHelper(Application.persistentDataPath, resourcesPath, codePath);
            DataObjectsManager.Init(Application.persistentDataPath, resourcesPath);
            yield return null;
#endif
        }

#if UNITY_WEBGL && !UNITY_EDITOR
        private static IEnumerator PreloadStreamingAssets(string resourcesPath)
        {
            var manifestPath = Path.Combine(resourcesPath, "balancy_files_manifest.txt");
            var manifestRequest = UnityWebRequest.Get(manifestPath);
            yield return manifestRequest.SendWebRequest();

            if (manifestRequest.result != UnityWebRequest.Result.Success)
            {
                Debug.LogWarning($"[Balancy] No manifest file found in StreamingAssets, skipping preload: {manifestRequest.error}");
                yield break;
            }

            var lines = manifestRequest.downloadHandler.text.Split('\n');
            int filesPreloaded = 0;

            foreach (var line in lines)
            {
                var relativePath = line.Trim().TrimStart('.', '/');
                if (string.IsNullOrEmpty(relativePath) || relativePath == "balancy_files_manifest.txt")
                    continue;

                var fileUrl = Path.Combine(resourcesPath, relativePath);
                var fileRequest = UnityWebRequest.Get(fileUrl);
                yield return fileRequest.SendWebRequest();

                if (fileRequest.result == UnityWebRequest.Result.Success)
                {
                    var fileData = fileRequest.downloadHandler.data;
                    Balancy.LibraryMethods.General.balancyPreloadFileFromStreamingAssets(relativePath, fileData, fileData.Length);
                    filesPreloaded++;
                }
                else
                {
                    Debug.LogWarning($"[Balancy] Failed to preload {relativePath}: {fileRequest.error}");
                }
            }

            Debug.Log($"[Balancy] Preloaded {filesPreloaded} files from StreamingAssets");
        }
#endif

#if UNITY_ANDROID && !UNITY_EDITOR
        private static bool IsTextFile(string relativePath)
        {
            var ext = Path.GetExtension(relativePath).ToLowerInvariant();
            return ext == ".json" || ext == ".txt" || ext == ".xml" || ext == ".csv" || ext == ".yaml" || ext == ".yml";
        }

        private static string ReadAssetAsString(AndroidJavaObject assetManager, string assetPath)
        {
            AndroidJavaObject inputStream = null;
            AndroidJavaObject reader = null;
            AndroidJavaObject bufferedReader = null;
            try
            {
                inputStream = assetManager.Call<AndroidJavaObject>("open", assetPath);
                reader = new AndroidJavaObject("java.io.InputStreamReader", inputStream, "UTF-8");
                bufferedReader = new AndroidJavaObject("java.io.BufferedReader", reader);

                var sb = new System.Text.StringBuilder();
                string line;
                while ((line = bufferedReader.Call<string>("readLine")) != null)
                {
                    if (sb.Length > 0)
                        sb.Append('\n');
                    sb.Append(line);
                }
                return sb.ToString();
            }
            finally
            {
                bufferedReader?.Call("close");
                reader?.Call("close");
                inputStream?.Call("close");
                bufferedReader?.Dispose();
                reader?.Dispose();
                inputStream?.Dispose();
            }
        }

        private static void PreloadAndroidTextResourcesSync(string streamingAssetsSubpath)
        {
            // Get AssetManager via JNI
            var unityPlayer = new AndroidJavaClass("com.unity3d.player.UnityPlayer");
            var activity = unityPlayer.GetStatic<AndroidJavaObject>("currentActivity");
            var assetManager = activity.Call<AndroidJavaObject>("getAssets");

            // Read manifest synchronously from AssetManager
            var subpath = streamingAssetsSubpath.TrimEnd('/');
            string manifestContent;
            try
            {
                manifestContent = ReadAssetAsString(assetManager, subpath + "/balancy_files_manifest.txt");
            }
            catch (Exception e)
            {
                Debug.LogWarning($"[Balancy] No manifest file found in StreamingAssets, skipping Android preload: {e.Message}");
                assetManager.Dispose();
                activity.Dispose();
                unityPlayer.Dispose();
                return;
            }

            var lines = manifestContent.Split('\n');

            foreach (var line in lines)
            {
                var relativePath = line.Trim().TrimStart('.', '/');
                if (string.IsNullOrEmpty(relativePath) || relativePath == "balancy_files_manifest.txt")
                    continue;

                if (IsTextFile(relativePath))
                {
                    try
                    {
                        var content = ReadAssetAsString(assetManager, subpath + "/" + relativePath);
                        Balancy.LibraryMethods.General.balancyAndroidPreloadResource(relativePath, content);
                    }
                    catch (Exception e)
                    {
                        Debug.LogWarning($"[Balancy] Failed to preload Android text resource {relativePath}: {e.Message}");
                    }
                }
                else
                {
                    Balancy.LibraryMethods.General.balancyAndroidSetResourceExists(relativePath, true);
                }
            }

            assetManager.Dispose();
            activity.Dispose();
            unityPlayer.Dispose();
        }
#endif
    }
}
